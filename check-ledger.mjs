import assert from 'node:assert/strict';
import {build} from 'esbuild';
const outfile=new URL('./ledger-test-bundle.mjs',import.meta.url).pathname.replace(/^\/(\w:)/,'$1');
await build({entryPoints:[new URL('./src/model.ts',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')],bundle:true,platform:'node',format:'esm',outfile});
const {budgetSchema,cashBalance,savingsBalance,forecast,totals,today}=await import('./ledger-test-bundle.mjs');
const day=today();
const entry=(id,kind,amount,status='done',direction='deposit')=>({id,name:id,kind,category:kind==='saving'?'Emergency fund':'Other',amount,date:day,status,essential:true,note:'',direction});
const oldBackup={entries:[entry('salary','income',1000),entry('rent','expense',200),entry('deposit','saving',300)],opening:500,openingDate:day,target:5000,caps:{}};
const budget=budgetSchema.parse(oldBackup);
assert.deepEqual(budget.adjustments,[],'Old backups gain an empty correction list');
assert.equal(budget.openingSavings,0,'Old backups retain a zero opening savings balance');
assert.equal(cashBalance(budget),1000);
assert.equal(savingsBalance(budget),300);
budget.openingSavings=50;
assert.equal(savingsBalance(budget),350,'Opening savings are independently editable');
budget.openingSavings=0;
budget.entries.push(entry('planned-bill','expense',700,'planned'));
assert.equal(cashBalance(budget),1000,'Planned bills do not change actual cash');
budget.entries.push(entry('withdrawal','saving',75,'done','withdrawal'));
assert.equal(cashBalance(budget),1075);
assert.equal(savingsBalance(budget),225);
assert.equal(totals(budget.entries).saved,225);
budget.adjustments.push({id:'cash-check',account:'cash',date:day,amount:-25,note:'Reconciled with bank'});
budget.adjustments.push({id:'savings-check',account:'savings',date:day,amount:10,note:'Reconciled savings'});
assert.equal(cashBalance(budget),1050);
assert.equal(savingsBalance(budget),235);
assert.equal(forecast(budget,day.slice(0,7)).closing,350,'Forecast includes planned bill and cash correction');
budget.adjustments.splice(0,1);
assert.equal(cashBalance(budget),1075,'Deleting a correction restores the ledger balance');
assert.ok(budgetSchema.safeParse(budget).success);
console.log('PASS: old backups, completed and planned entries, transfers both ways, manual corrections, forecast, correction removal.');
