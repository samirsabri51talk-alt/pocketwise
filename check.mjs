import assert from 'node:assert/strict';
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import 'fake-indexeddb/auto';
await build({entryPoints:[new URL('./src/storage.ts',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')],bundle:true,platform:'node',format:'esm',outfile:new URL('./test-storage.mjs',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')});
const {readBudget,writeBudget,markSynced,replaceFromCloud}=await import('./test-storage.mjs');
const blank={entries:[],opening:0,openingDate:'2026-10-01',target:30000,caps:{}};
assert.equal((await readBudget()).revision,0);
assert.equal(await writeBudget(blank,0),1);
assert.equal(await writeBudget({...blank,opening:1234.5},1),2);
assert.equal((await readBudget()).data.opening,1234.5);
await assert.rejects(writeBudget({...blank,opening:999},1),/another window/);
assert.equal((await readBudget()).data.opening,1234.5,'Stale write must not alter data');
await assert.rejects(writeBudget({...blank,target:-100},2));
const results=await Promise.allSettled([writeBudget({...blank,opening:10},2),writeBudget({...blank,opening:20},2)]);
assert.equal(results.filter(x=>x.status==='fulfilled').length,1,'Concurrent writes use atomic revisions');
assert.equal((await readBudget('user-a')).data,null,'Account workspaces start separately from guest data');
assert.equal(await writeBudget(blank,0,'user-a',true),1);
assert.equal((await readBudget('user-a')).sync.syncedRevision,1,'An untouched account seed is clean');
assert.equal((await readBudget('user-b')).data,null,'Different accounts cannot see another local budget');
await markSynced('user-a',1,4);
assert.equal(await writeBudget({...blank,opening:50},1,'user-a'),2);
assert.deepEqual((await readBudget('user-a')).sync,{remoteVersion:4,syncedRevision:1},'Local edits remain pending after sync');
assert.equal(await replaceFromCloud('user-a',{...blank,opening:70},2,5),3);
assert.deepEqual((await readBudget('user-a')).sync,{remoteVersion:5,syncedRevision:3},'Cloud download becomes clean');
const out=new URL('../../outputs/Pocketwise-Offline/',import.meta.url);
for(const f of ['index.html','app.js','app.css','manifest.webmanifest','sw.js','icon-192.png','icon-512.png'])assert.ok((await fs.stat(new URL(f,out))).size>0,f);
const js=await fs.readFile(new URL('app.js',out),'utf8');assert.ok(!js.includes('/api/budget'));assert.ok(!js.includes('signin-with-chatgpt'));assert.ok(!js.includes('import-2026'),'Financial records must not be in public app assets');
const css=await fs.readFile(new URL('app.css',out),'utf8');assert.ok(!css.includes('fonts.googleapis'));
console.log('PASS: offline database, account isolation, sync cursors, validation, concurrency, PWA assets, no embedded personal transactions.');
